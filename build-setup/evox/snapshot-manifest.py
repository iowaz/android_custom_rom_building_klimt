#!/usr/bin/env python3
"""Turn `repo manifest -r` of the Evo tree into a self-contained snapshot for the public build repo.

usage: snapshot-manifest.py <pinned.xml from `repo manifest -r`> <out.xml> [--check]

- device/kernel and the forked Evo projects point at the iowaz repos (that is where their pinned commits live);
- the projects patched by device/xiaomi/klimt/patches/tree go back to their BASES commit (apply.sh adds the rest);
- the private proprietary vendor repo is added (it is copied into the tree, so repo does not list it).
--check asks GitHub (gh api compare) whether every pinned GitHub commit is still on its branch upstream.
Needs the GitHub CLI (gh), logged in with access to the private iowaz repos.
"""
import json, re, subprocess, sys
from concurrent.futures import ThreadPoolExecutor

src, dst = sys.argv[1], sys.argv[2]
check = "--check" in sys.argv[3:]

def gh(*args):
    r = subprocess.run(["gh", "api", *args], capture_output=True, text=True)
    return r.stdout.strip() if r.returncode == 0 else None

def raw(repo, path, ref):
    return gh(f"repos/{repo}/contents/{path}?ref={ref}", "-H", "Accept: application/vnd.github.raw")

DEVICE = "iowaz/android_device_xiaomi_klimt"
bases = dict(l.split() for l in raw(DEVICE, "patches/tree/BASES", "evox").splitlines() if l.strip())
vendor_sha = gh("repos/iowaz/proprietary_vendor_xiaomi_klimt/commits/evox", "-q", ".sha")
assert vendor_sha and len(vendor_sha) == 40, "cannot read iowaz/proprietary_vendor_xiaomi_klimt (gh auth?)"

# path -> (iowaz repo name, branch). Only klimt-specific changes have a fork. evox17 dropped the
# evox16 Settings, hardware/xiaomi and libdmabufheap forks (back on upstream); their branches stay
# for the evox16 snapshot.
FORKS = {
    "device/xiaomi/klimt": ("android_device_xiaomi_klimt", "evox"),
    "kernel/xiaomi/klimt": ("android_kernel_xiaomi_klimt", "17.0"),
    "build/soong": ("build_soong", "evox16"),
    "hardware/interfaces": ("hardware_interfaces", "cnb-klimt"),
    "frameworks/native": ("frameworks_native", "evox16"),
}
# path -> (remote, name, branch): back on upstream (evox16 has none of our commits there)
UPSTREAM = {
    "vendor/lineage": ("evo", "vendor_evolution", "cnb"),
}

def attr(line, k):
    m = re.search(rf'\b{k}="([^"]*)"', line)
    return m.group(1) if m else None

def setattr_(line, k, v):
    if attr(line, k) is None:
        return line.replace("<project ", f'<project {k}="{v}" ', 1)
    return re.sub(rf'\b{k}="[^"]*"', f'{k}="{v}"', line, count=1)

text = open(src, encoding="utf-8").read()
remotes = {attr(l, "name"): attr(l, "fetch") for l in text.splitlines() if l.strip().startswith("<remote ")}
out, seen = [], set()
for line in text.splitlines():
    s = line.strip()
    if s.startswith("<remote ") and attr(s, "name") == "evo":
        out.append(line)
        if "iowaz" not in remotes:
            out.append('  <remote name="iowaz" fetch="https://github.com/iowaz"/>')
        continue
    if s.startswith("<project "):
        path = attr(s, "path") or attr(s, "name")
        if path == "vendor/xiaomi/klimt":  # a repo project since evox16: pin it like the others
            line = setattr_(line, "revision", vendor_sha)
            for k, v in (("name", "proprietary_vendor_xiaomi_klimt"), ("remote", "iowaz"), ("upstream", "evox"), ("dest-branch", "evox")):
                line = setattr_(line, k, v)
            seen.add(path)
        elif path in FORKS:
            name, branch = FORKS[path]
            for k, v in (("name", name), ("remote", "iowaz"), ("upstream", branch), ("dest-branch", branch)):
                line = setattr_(line, k, v)
            seen.add(path)
        elif path in UPSTREAM:
            remote, name, branch = UPSTREAM[path]
            for k, v in (("name", name), ("remote", remote), ("upstream", branch), ("dest-branch", branch)):
                line = setattr_(line, k, v)
            seen.add(path)
        elif path in bases:
            line = setattr_(line, "revision", bases[path])
            seen.add(path)
    if s == "</manifest>" and "vendor/xiaomi/klimt" not in seen:
        out.append("  <!-- private: proprietary blobs (Git LFS); not a repo project in the live tree, added here -->")
        out.append(f'  <project path="vendor/xiaomi/klimt" name="proprietary_vendor_xiaomi_klimt" remote="iowaz" '
                   f'revision="{vendor_sha}" upstream="evox" dest-branch="evox"/>')
    out.append(line)
missing = (set(FORKS) | set(UPSTREAM) | set(bases)) - seen
assert not missing, f"not found in the pinned manifest: {missing}"

header = ("<!-- Snapshot of the klimt Evolution X tree, generated by build-setup/evox/snapshot-manifest.py from\n"
          "     `repo manifest -r`. Every project is pinned. Projects listed in device/xiaomi/klimt/patches/tree/BASES\n"
          "     are pinned to that base: run patches/tree/apply.sh after syncing. -->\n")
body = "\n".join(out) + "\n"
body = body.replace("<manifest>", header + "<manifest>", 1)
open(dst, "w", encoding="utf-8", newline="\n").write(body)
print(f"wrote {dst}: {body.count('<project ')} projects; forks -> iowaz: {len(FORKS)}; patched -> BASES: {len(bases)}")

if check:
    # Which pinned commits can still be fetched from their GitHub branch (compare: behind/identical = reachable)
    jobs = []
    default = next(attr(l, "remote") for l in body.splitlines() if l.strip().startswith("<default "))
    for line in body.splitlines():
        s = line.strip()
        if not s.startswith("<project "):
            continue
        rem = attr(s, "remote") or default
        fetch = remotes.get(rem) or ("https://github.com/iowaz" if rem == "iowaz" else "")
        if fetch == "..":
            fetch = "https://github.com"
        if not fetch.startswith("https://github.com"):
            continue
        owner = fetch.rstrip("/").split("/")[3:] if fetch.rstrip("/") != "https://github.com" else []
        repo = "/".join(owner + [attr(s, "name")])
        branch = (attr(s, "upstream") or "").replace("refs/heads/", "")
        jobs.append((attr(s, "path") or attr(s, "name"), repo, branch, attr(s, "revision")))
    def cmp(j):
        path, repo, branch, sha = j
        if not branch:  # pinned by SHA only (no upstream recorded): can the commit still be fetched?
            return path, repo, branch, sha, "exists" if gh(f"repos/{repo}/commits/{sha}", "-q", ".sha") else "NOT FOUND"
        r = gh(f"repos/{repo}/compare/{branch}...{sha}", "-q", ".status")
        return path, repo, branch, sha, r or "NOT FOUND"
    res = list(ThreadPoolExecutor(8).map(cmp, jobs))
    bad = [r for r in res if r[4] not in ("behind", "identical", "exists")]
    print(f"checked {len(res)} GitHub projects; pinned commit no longer on its branch: {len(bad)}")
    for path, repo, branch, sha, st in sorted(bad):
        print(f"  {st:10} {path}  ({repo} {branch} @ {sha[:10]})")
